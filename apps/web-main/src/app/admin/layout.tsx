export default function AdminLayout({ children }: { children: ReactNode }) {
  const { user, isReady } = useRequireAuth();
  const router = useRouter();
  const pathname = usePathname();
  const [isAdmin, setIsAdmin] = useState(false);

  useEffect(() => {
    if (isReady && !['ADMIN', 'SUPERADMIN'].includes(user?.role || '')) {
      router.replace('/');
    }
    if (isReady && ['ADMIN', 'SUPERADMIN'].includes(user?.role || '')) {
      setIsAdmin(true);
    }
  }, [isReady, user, router]);

  // One small groupBy; only fetched once the admin check has passed.
  const { data: reviewCounts } = useClinicReviewCounts(isAdmin);
  const pendingClinics = reviewCounts?.pending ?? 0;

  const activeHref = sidebarItems
    .filter((i) => pathname === i.href || (i.href !== '/admin' && pathname.startsWith(i.href + '/')))
    .reduce<string | null>((best, i) => (!best || i.href.length > best.length ? i.href : best), null);

  if (!isReady || !isAdmin) {
    return (
      <DashboardSkeleton />
    );
  }

  return (
    <div className="min-h-screen flex bg-gray-50/50">
      {/* Sidebar */}
      <aside className="w-60 bg-white border-r border-gray-100 flex flex-col fixed inset-y-0 left-0 z-40">
        <div className="p-4 border-b border-gray-100">
          <a href="/" className="flex items-center gap-2">
            <Image src="/logo.png" alt="Upllyft" className="h-8 w-auto" width={59} height={32} priority />
          </a>
          <p className="mt-1 text-xs text-gray-500">Admin Console</p>
        </div>
        <nav className="flex-1 px-2 py-3 space-y-1 overflow-y-auto">
          {sidebarItems.map((item) => {
            // Longest matching prefix wins, so /admin/clinics/review highlights
            // "Clinic approvals" rather than "Clinics" as well.
            const isActive = item.href === activeHref;
            const badge = 'badgeKey' in item && item.badgeKey === 'clinicReview' ? pendingClinics : 0;
            return (
              <Link
                key={item.href}
                href={item.href}
                className={`flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium transition-colors ${isActive
                  ? 'bg-teal-50 text-teal-700'
                  : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900'
                  }`}
              >
                <span className="flex-shrink-0">{item.icon}</span>
                <span>{item.label}</span>
                {badge > 0 && (
                  <span className="ml-auto min-w-5 h-5 px-1.5 rounded-full bg-amber-100 text-amber-800 text-xs font-semibold flex items-center justify-center">
                    {badge}
                  </span>
                )}
              </Link>
            );
          })}
        </nav>
        <div className="p-3 border-t border-gray-100 space-y-1">
          <a
            href="/"
            className="flex items-center gap-3 px-3 py-2.5 rounded-xl text-sm font-medium text-gray-600 hover:bg-gray-50 hover:text-gray-900 transition-colors"
          >
            <svg className="w-5 h-5 flex-shrink-0" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M11 17l-5-5m0 0l5-5m-5 5h12" />
            </svg>
            <span>Back to App</span>
          </a>
          <SignOutButton />
        </div>
      </aside>

      {/* Main content */}
      <main className="flex-1 ml-60">
        <div className="max-w-7xl mx-auto px-6 py-8">
          {children}
        </div>
      </main>
    </div>
  );
}
